#!/usr/bin/env node
// Turns the wasm-bindgen output in target/wasm-bindgen into js/wasm: the wasm split in parts (see
// split-wasm.mjs) and its glue, the lazily loaded assets, their licence notices, and the pins that src/assets.ts checks.
// The pins are written here and only here, so a rebuilt wasm cannot be out of date with them.
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import zlib from "node:zlib";

import { splitWasm } from "./split-wasm.mjs";

const root = path.resolve(import.meta.dirname, "..");
const from = (...parts) => path.join(root, ...parts);
const out = (name) => path.join(root, "js/wasm", name);
fs.mkdirSync(out(""), { recursive: true });

// The glue, as a factory. wasm-bindgen's glue keeps its instance in module scope, so one
// module record per instance would pin every retired instance's memory for the life of the
// process. Each createGlue() call is a fresh closure the GC can collect with its instance.
let body = fs.readFileSync(from("target/wasm-bindgen/recto.js"), "utf8");
const names = [...body.matchAll(/^export (?:class|function) (\w+)/gmu)].map((m) => m[1]);
const tail = "export { initSync, __wbg_init as default };";
if (!body.includes(tail) || names.length === 0) {
  throw new Error("unexpected wasm-bindgen glue shape; update scripts/package-wasm.mjs");
}
// The placeholders a part's functions stand on until the part is loaded come from src/engine.ts.
const glueImports = '"./recto_bg.js": import0,';
if (!body.includes(glueImports)) {
  throw new Error("unexpected wasm-bindgen glue imports; update scripts/package-wasm.mjs");
}
body = body
  .replace(/^export (class|function) /gmu, "$1 ")
  .replace(tail, "")
  .replace(glueImports, `${glueImports} ...placeholders,`);
fs.writeFileSync(
  out("recto.gen.mjs"),
  `// Generated by scripts/package-wasm.mjs from wasm-bindgen's glue.\n` +
    `export function createGlue(placeholders) {\n${body}\nreturn { ${[...names, "initSync"].join(", ")} };\n}\n`,
);
// A typed array the engine returns is always a copy out of WASM memory, so it owns an
// ArrayBuffer (parameters stay as wide as wasm-bindgen writes them), and the asset loader
// gets its real signature instead of `Function`.
fs.writeFileSync(
  out("recto.types.d.mts"),
  fs
    .readFileSync(from("target/wasm-bindgen/recto.d.ts"), "utf8")
    .replace(
      /(\)|readonly \w+): ((?:Uint8|Uint32|Int32|Float32|Float64)Array);/gu,
      "$1: $2<ArrayBuffer>;",
    )
    .replace(
      "setAssetLoader(loader: Function)",
      "setAssetLoader(loader: (index: number) => Uint8Array | undefined)",
    ),
);
fs.writeFileSync(
  out("recto.gen.d.mts"),
  `import type * as Glue from "./recto.types.mjs";\n` +
    `export declare function createGlue(placeholders: Record<string, object>): Pick<typeof Glue, ${[...names, "initSync"].map((n) => JSON.stringify(n)).join(" | ")}>;\n`,
);
splitWasm(from("target/wasm-bindgen/recto_bg.wasm"), out(""));
// The table a part's functions are called through: wasm-split adds it last, and exports it.
const partTable = WebAssembly.Module.exports(new WebAssembly.Module(fs.readFileSync(out("recto.wasm"))))
  .filter((entry) => entry.kind === "table" && entry.name.startsWith("%"))
  .at(-1).name;
fs.appendFileSync(out("recto.gen.mjs"), `export const PART_TABLE = ${JSON.stringify(partTable)};\n`);
fs.appendFileSync(out("recto.gen.d.mts"), "export declare const PART_TABLE: string;\n");

// fonts.bin: u32 count, u32 offsets[count + 1], bytes (little-endian). hayro-font's Foxit
// fonts, in the order of `font_index` in crates/recto/src/assets.rs.
const FONTS = [
  "Fixed", "FixedBold", "FixedBoldItalic", "FixedItalic",
  "Sans", "SansBold", "SansBoldItalic", "SansItalic",
  "Serif", "SerifBold", "SerifBoldItalic", "SerifItalic",
  "Symbol", "Dingbats",
].map((name) => fs.readFileSync(from(`vendor/hayro-font/assets/Foxit${name}.pfb`)));
const header = new Uint32Array(FONTS.length + 2);
header[0] = FONTS.length;
FONTS.forEach((font, i) => {
  header[i + 2] = header[i + 1] + font.byteLength;
});
fs.writeFileSync(out("fonts.bin"), Buffer.concat([Buffer.from(header.buffer), ...FONTS]));

fs.copyFileSync(from("assets/cjk-fallback.ttf"), out("cjk-fallback.ttf"));
// Raw deflate: the wasm has an inflate, and no longer carries brotli's decoder and dictionary.
fs.writeFileSync(
  out("cmaps.deflate"),
  zlib.deflateRawSync(zlib.brotliDecompressSync(fs.readFileSync(from("vendor/hayro-cmap/assets/cmaps.brotli"))), { level: 9 }),
);

// Everything the shipped files are made from, with its licence.
const section = (title, text) => `${"=".repeat(78)}\n${title}\n${"=".repeat(78)}\n\n${text.trim()}\n\n`;
let notices =
  "Third-party notices for the files in this directory. recto itself is MIT licensed.\n\n" +
  section("Droid Sans Fallback (cjk-fallback.ttf)", fs.readFileSync(from("assets/cjk-fallback.NOTICE"), "utf8")) +
  section("Foxit fonts (fonts.bin)", fs.readFileSync(from("vendor/hayro-font/assets/LICENSE_FOXIT"), "utf8")) +
  section("Adobe CMap resources (cmaps.deflate)", fs.readFileSync(from("vendor/hayro-cmap/assets/LICENSE.txt"), "utf8")) +
  section("ICC profiles (compiled into recto.wasm)", fs.readFileSync(from("vendor/hayro-interpret/assets/CGATS_LICENSE.txt"), "utf8"));
const cargo = (...args) => execFileSync("cargo", args, { cwd: root, encoding: "utf8", maxBuffer: 1 << 28 });
const selection = ["--no-default-features", "--features", "wasm", "--target", "wasm32-unknown-unknown"];
const compiled = new Set(
  cargo("tree", "-p", "recto", "-e", "normal", "--prefix", "none", "--format", "{p}", ...selection)
    .split("\n")
    .map((line) => line.split(" ").slice(0, 2).join("@")),
);
const { packages } = JSON.parse(cargo("metadata", "--format-version", "1", "--locked"));
const crates = packages
  .filter((p) => p.name !== "recto" && compiled.has(`${p.name}@v${p.version}`))
  .sort((a, b) => a.name.localeCompare(b.name));
for (const crate of crates) {
  const dir = path.dirname(crate.manifest_path);
  // MIT where a crate offers the choice: the shorter text, and it carries the copyright.
  const file = ["LICENSE-MIT", "LICENSE-MIT.md", "LICENSE.md", "LICENSE", "LICENSE.txt", "COPYING"].find((f) =>
    fs.existsSync(path.join(dir, f)),
  );
  notices += section(
    `${crate.name} ${crate.version} (compiled into recto.wasm; ${crate.license})`,
    file ? fs.readFileSync(path.join(dir, file), "utf8") : `Licensed ${crate.license}; the crate ships no licence file.`,
  );
}
fs.writeFileSync(out("THIRD_PARTY_NOTICES"), notices);

const sha256 = (name) => createHash("sha256").update(fs.readFileSync(out(name))).digest("hex");
const pinned = ["recto.wasm", "recto-render.wasm", "recto-more.wasm", "recto-rare.wasm", "fonts.bin", "cjk-fallback.ttf", "cmaps.deflate"];
fs.writeFileSync(
  out("pins.mjs"),
  `// Generated by scripts/package-wasm.mjs.\nexport const PINS = ${JSON.stringify(Object.fromEntries(pinned.map((n) => [n, sha256(n)])), null, 2)};\n`,
);
fs.writeFileSync(
  out("pins.d.mts"),
  `export declare const PINS: Record<${pinned.map((n) => JSON.stringify(n)).join(" | ")}, string>;\n`,
);
console.log(`recto.wasm ${sha256("recto.wasm")}`);
